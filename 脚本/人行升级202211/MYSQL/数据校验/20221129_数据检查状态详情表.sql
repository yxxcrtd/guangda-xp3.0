DROP TABLE IF EXISTS PBC_REPORT_GENERAT_CHECKDETAIL;
CREATE TABLE `PBC_REPORT_GENERAT_CHECKDETAIL`  (
  `UUID` varchar(36) NOT NULL COMMENT '主键',
  `CHECK_UUID` varchar(50) DEFAULT NULL COMMENT '数据检查uuid',
  `CHECK_RESULT` varchar(1000) DEFAULT NULL COMMENT '结果错误信息',
  `CHECK_FLAG` varchar(1) DEFAULT NULL COMMENT '检查状态- 0-成功,1-失败',
  `CHECK_DATA` varchar(1000) DEFAULT NULL COMMENT '错误数据-值',
  `RULE_ID` varchar(100) DEFAULT NULL COMMENT '规则编号',
  `CREATE_TIME` datetime DEFAULT NULL COMMENT '创建日期',
  `UPDATE_TIME` datetime DEFAULT NULL COMMENT '更新日期',
  `CREATE_USER` varchar(50) DEFAULT NULL COMMENT '创建人',
  `CREATE_DEPT` varchar(10) DEFAULT NULL COMMENT '创建部门',
  `UPDATE_USER` varchar(10) DEFAULT NULL COMMENT '更新人',
  `STATUS` varchar(50) NULL DEFAULT NULL COMMENT '数据状态',
   PRIMARY KEY (`UUID`)
) ENGINE=InnoDB COMMENT = '数据检查状态详情表';