COMMENT ON COLUMN PBC_TARGET_INFO_ERRORDATA.INDENTIFY_MARK IS '识别标识';
COMMENT ON COLUMN PBC_TARGET_INFO_ERRORDATA.PBC_PROD_ID IS '人行产品代码';
COMMENT ON COLUMN PBC_TARGET_INFO_ERRORDATA.HOLDER_NAME IS '投资者名称';
COMMENT ON COLUMN PBC_TARGET_INFO_ERRORDATA.HOLDER_TYPE IS '投资者类别';
COMMENT ON COLUMN PBC_TARGET_INFO_ERRORDATA.HOLD_DATE IS '持有日期';
COMMENT ON COLUMN PBC_TARGET_INFO_ERRORDATA.CCY IS '币种';
COMMENT ON COLUMN PBC_TARGET_INFO_ERRORDATA.QTY IS '持有份额';
COMMENT ON COLUMN PBC_TARGET_INFO_ERRORDATA.AMOUNT IS '持有金额';
COMMENT ON COLUMN PBC_TARGET_INFO_ERRORDATA.STATUS IS '数据状态';
COMMENT ON COLUMN PBC_TARGET_INFO_ERRORDATA.ERR_MSG IS '错误信息';
COMMENT ON COLUMN PBC_TARGET_INFO_ERRORDATA.ORG_DATA IS '原始数据';
COMMENT ON COLUMN PBC_TARGET_INFO_ERRORDATA.CREATE_USER IS '创建人';
COMMENT ON COLUMN PBC_TARGET_INFO_ERRORDATA.CREATE_DEPT IS '创建部门';
