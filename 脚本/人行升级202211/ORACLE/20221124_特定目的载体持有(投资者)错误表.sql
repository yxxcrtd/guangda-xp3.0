DROP TABLE PBC_TARGET_INFO_ERRORDATA;
CREATE TABLE PBC_TARGET_INFO_ERRORDATA (
   UUID VARCHAR2(36),
   ACCOUNT VARCHAR2(50),
   INDENTIFY_MARK VARCHAR2(30),
   PBC_PROD_ID VARCHAR2(100),
   HOLDER_NAME VARCHAR2(200),
   HOLDER_TYPE VARCHAR2(2),
   HOLD_DATE DATE,
   CCY VARCHAR2(10),
   QTY DECIMAL(32,2),
   AMOUNT DECIMAL(32,2),
   CREATE_TIME TIMESTAMP(6),
   UPDATE_TIME TIMESTAMP(6),
   CREATE_USER VARCHAR2(20),
   CREATE_DEPT VARCHAR2(20),
   UPDATE_USER VARCHAR2(20),
   STATUS VARCHAR2(50),
   ERR_MSG VARCHAR2(1000),
   ORG_DATA VARCHAR2(1000)
);
COMMENT ON TABLE PBC_TARGET_INFO_ERRORDATA IS '特定目的载体持有信息（投资者）错误信息表';
