CREATE TABLE CHB_BRANCH_NETWORK
(
    BRANCH_NO VARCHAR(20) NOT NULL COMMENT '网点编号',
    BRANCH_NAME VARCHAR(250) NOT NULL COMMENT '网点名称',
    BRANCH_FSA VARCHAR(2) NOT NULL COMMENT '网点所属监管码值',
    NETWORK_NO VARCHAR(10) NOT NULL COMMENT '网点地区码值',
    REMARK VARCHAR(200) NULL COMMENT '备注',
    STATUS CHAR(1) DEFAULT 'E' NOT NULL COMMENT '数据状态',
    CREATE_USER VARCHAR(20) NOT NULL COMMENT '创建人',
    CREATE_TIME DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    UPDATE_USER VARCHAR(20) NOT NULL COMMENT '更新人',
    UPDATE_TIME DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '修改时间',
    PRIMARY KEY (BRANCH_NO)
)
    ENGINE=InnoDB DEFAULT CHARSET=utf8 COMMENT='网点信息表';

